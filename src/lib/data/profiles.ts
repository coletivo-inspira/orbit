import type { AppId, AppPresence, AvatarConfig, Profile } from "@/lib/types";

type ProfileSpec = Omit<Profile, "dist" | "photo">;

function profile(spec: ProfileSpec): Profile {
  return { ...spec, dist: formatDistance(spec.distanceM), photo: `${spec.id}.webp` };
}

function av(bg: string, skin: string, hair: string, shirt: string, accessory: AvatarConfig["accessory"] = "none") {
  return { bg, skin, hair, shirt, accessory };
}

/** Presence-only badges plus handles for apps that link out. */
function apps(presence: AppId[], handles: Partial<Record<AppId, string>> = {}): Partial<Record<AppId, AppPresence>> {
  const result: Partial<Record<AppId, AppPresence>> = {};
  for (const id of presence) result[id] = { active: true };
  for (const [id, handle] of Object.entries(handles) as [AppId, string][]) result[id] = { active: true, handle };
  return result;
}

